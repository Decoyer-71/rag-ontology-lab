class BM25:
    """BM25 검색기.

    ⚠⚠ 한 문장 직관:
      「이 단어가 **이 문서에 유난히 많이** 나오는가」 × 「이 단어가 **원래 흔한 단어인가**」
      를 곱해 점수를 낸다. 그리고 **문서가 긴 것을 보정한다.**

    세 항이 각각 무엇을 하는지 설명할 수 있어야 이 단계가 닫힌다:
      · IDF        — 흔한 단어의 기여를 깎는다
      · TF 포화     — 같은 단어가 100번 나와도 10번 나온 것의 10배가 되지 않게 한다
      · 길이 정규화 — 긴 문서가 단지 길다는 이유로 이기지 않게 한다

    Args:
        k1: TF 포화 정도. 클수록 빈도에 더 민감해진다. 관행값 1.2~2.0
        b: 길이 정규화 강도. 0 이면 길이를 무시, 1 이면 완전 보정. 관행값 0.75

    ⚠ `k1`·`b` 는 **매직 넘버가 아니라 결정 사항이다.** 왜 그 값인지 주석에 적어라.
      그리고 Stage 5 에서 이 값을 흔들어 결론이 유지되는지 확인하라(민감도).
    """

